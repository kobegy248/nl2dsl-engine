"""Test cases for the statistics-driven SQL optimization evaluation cases (Task 6).

V2 framework scores at DSL/Planner level; SQL-layer optimizations (like routing,
type alignment, join reorder) are verified by unit tests in
``tests/unit/test_sql_builder.py``.  These evaluation cases verify end-to-end
DSL-level semantic correctness — i.e. the *inputs* that feed the SQL-builder
optimizations are correctly generated by the pipeline.

Covered cases:
  - LIKE_INDEXED_001: date query on indexed+high-selectivity ``order_date``
    (rule generator emits ``time_range``, not ``like``; like prefix compilation
    is SQL-layer, covered by ``test_like_prefix_match_for_indexed_high_selectivity``)
  - FILTER_TYPE_001: numeric filter on ``price``
    (rule generator emits ``value=100.0`` float, not string; string→int type
    alignment is SQL-layer, covered by
    ``test_filter_value_type_aligned_numeric_string_to_int``)

JOIN_SMALL_001 was removed: the join-path DSL coverage is already provided by
JOIN_002 in ``joins.yaml`` (identical query "按供应商统计销售额"), and join
reorder is a SQL-builder optimization verified by
``test_join_reordered_small_drives_large``.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from nl2dsl.evaluation.dataset import V2DatasetLoader
from nl2dsl.evaluation.execution import (
    ApiEvaluationExecutor,
    ExecutorConfig,
)

FIXTURES = Path(__file__).resolve().parents[2] / "e2e" / "fixtures"
DATASET_V2 = Path(__file__).resolve().parents[2] / "evaluation" / "dataset" / "v2"


@pytest.fixture(scope="module")
def executor_config() -> ExecutorConfig:
    from tests.e2e.mock_data import create_mock_database

    engine, *_ = create_mock_database("sqlite:///:memory:")
    metrics = yaml.safe_load((FIXTURES / "metrics_test.yaml").read_text(encoding="utf-8"))
    perm = yaml.safe_load((FIXTURES / "permissions_test.yaml").read_text(encoding="utf-8"))
    registry = {
        "metrics": metrics.get("metrics", {}),
        "dimensions": metrics.get("dimensions", {}),
        "data_sources": metrics.get("data_sources", {}),
        "permissions": perm.get("users", {}),
    }
    return ExecutorConfig(
        engine=engine,
        registry_dict=registry,
        permissions=perm.get("users", {}),
        sensitive_columns=perm.get("sensitive_columns", {}),
        masking_rules=perm.get("masking_rules", {}),
        llm_client=None,
    )


def _load_v2_cases():
    return V2DatasetLoader(DATASET_V2).load_all()


def _find_case(case_id: str):
    cases = _load_v2_cases()
    return next(c for c in cases if c.id == case_id)


def _find_filter(filters: list[dict], field: str) -> dict | None:
    """Find a filter by field name, ignoring governance-injected filters."""
    for f in filters or []:
        if f.get("field") == field:
            return f
    return None


# =============================================================================
# Case loading + schema validation
# =============================================================================


class TestSqlOptimizationCasesLoad:
    """Verify the dataset cases load with valid schema."""

    def test_like_indexed_case_loads(self):
        case = _find_case("LIKE_INDEXED_001")
        assert case.query == "2026年7月的销售额"
        assert case.expected["intent"] == "aggregate"
        assert case.expected["metric"] == "sales_amount"
        planner = case.expected.get("planner", {})
        assert planner.get("time_field") == "order_date"
        assert planner.get("time_range") == ["2026-07-01", "2026-07-31"]

    def test_filter_type_case_loads(self):
        case = _find_case("FILTER_TYPE_001")
        assert case.query == "价格大于100的销售额"
        assert case.expected["intent"] == "aggregate"
        assert case.expected["metric"] == "sales_amount"
        filters = case.expected.get("filters") or []
        assert len(filters) == 1
        assert filters[0]["field"] == "price"
        assert filters[0]["operator"] == ">"
        assert filters[0]["value"] == 100


# =============================================================================
# Pipeline execution (verify DSL-level behavior, not just "didn't crash")
# =============================================================================


class TestSqlOptimizationCasesExecute:
    """Verify the cases execute through the real pipeline and produce the
    expected DSL-level fields (filters / time_range / metrics)."""

    def test_like_indexed_prefix_match_executes(self, executor_config):
        """LIKE_INDEXED_001 exercises the order_date (indexed+high selectivity) path.

        The rule-based generator resolves '2026年7月' into a time_range on
        order_date. The SQL builder applies prefix-match optimization for
        like filters on indexed+high-selectivity columns (verified in
        test_sql_builder.py::test_like_prefix_match_for_indexed_high_selectivity).
        """
        case = _find_case("LIKE_INDEXED_001")
        executor = ApiEvaluationExecutor(executor_config)
        obs = executor.execute(case, generator_mode="rule", optimizer_enabled=False)
        assert obs.status != "error", f"Pipeline error: {obs.error}"

        # Verify DSL-level behavior: time_range resolved on order_date.
        dsl = obs.final_dsl
        assert dsl.get("time_field") == "order_date", (
            f"Expected time_field='order_date', got {dsl.get('time_field')!r}"
        )
        time_range = dsl.get("time_range")
        assert time_range is not None, "Expected time_range to be resolved"
        assert len(time_range) == 2, f"Expected 2-element time_range, got {time_range}"
        # Metrics present
        assert dsl.get("metrics"), "Expected metrics in output DSL"

    def test_filter_type_alignment_executes(self, executor_config):
        """FILTER_TYPE_001 exercises the numeric filter path on price.

        The rule-based generator produces a numeric filter (price > 100.0).
        The SQL builder aligns string values to the column's numeric type
        (verified in test_sql_builder.py::test_filter_value_type_aligned_numeric_string_to_int).
        """
        case = _find_case("FILTER_TYPE_001")
        executor = ApiEvaluationExecutor(executor_config)
        obs = executor.execute(case, generator_mode="rule", optimizer_enabled=False)
        assert obs.status != "error", f"Pipeline error: {obs.error}"

        # Verify DSL-level behavior: price filter present in output DSL.
        dsl = obs.final_dsl
        filters = dsl.get("filters") or []
        price_filter = _find_filter(filters, "price")
        assert price_filter is not None, (
            f"Expected price filter in output DSL, got filters={filters}"
        )
        assert price_filter.get("operator") == ">"
        assert price_filter.get("value") == 100 or price_filter.get("value") == 100.0
        # Metrics present
        assert dsl.get("metrics"), "Expected metrics in output DSL"
